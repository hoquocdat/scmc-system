import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  ArrayMinSize,
  IsArray,
  IsEnum,
  IsIn,
  IsInt,
  IsNotEmpty,
  IsNumber,
  IsOptional,
  IsPositive,
  IsString,
  IsUUID,
  Max,
  MaxLength,
  Min,
  ValidateNested,
} from 'class-validator';

export class CheckoutLineDto {
  @ApiProperty() @IsUUID() product_id: string;

  @ApiPropertyOptional() @IsOptional() @IsUUID() product_variant_id?: string;

  @ApiProperty({ minimum: 1 }) @IsInt() @Min(1) quantity: number;

  @ApiProperty({
    description:
      'Unit price the POS displayed; rejected with PRICE_CHANGED when the server price differs',
  })
  @IsNumber()
  @Min(0)
  expected_unit_price: number;

  @ApiPropertyOptional({ description: 'Line discount per unit (VND)' })
  @IsOptional()
  @IsNumber()
  @Min(0)
  discount_amount?: number;

  @ApiPropertyOptional()
  @IsOptional()
  @IsString()
  @MaxLength(500)
  notes?: string;
}

export class CheckoutDiscountDto {
  @ApiProperty({ enum: ['fixed', 'percent'] })
  @IsIn(['fixed', 'percent'])
  type: 'fixed' | 'percent';

  @ApiProperty({ description: 'Amount (VND) or percent' })
  @IsNumber()
  @Min(0)
  value: number;
}

export enum CheckoutPaymentMethod {
  CASH = 'cash',
  CARD = 'card',
  BANK_TRANSFER = 'bank_transfer',
  EWALLET_MOMO = 'ewallet_momo',
  EWALLET_ZALOPAY = 'ewallet_zalopay',
  EWALLET_VNPAY = 'ewallet_vnpay',
}

export class CheckoutPaymentDto {
  @ApiProperty({ enum: CheckoutPaymentMethod })
  @IsEnum(CheckoutPaymentMethod)
  method: CheckoutPaymentMethod;

  @ApiProperty({ description: 'Amount applied to the order' })
  @IsNumber()
  @IsPositive()
  amount: number;

  @ApiPropertyOptional({
    description: 'Cash handed over (cash only); change = tendered - amount',
  })
  @IsOptional()
  @IsNumber()
  @Min(0)
  amount_tendered?: number;

  @ApiPropertyOptional({ description: 'Card/transfer/e-wallet reference' })
  @IsOptional()
  @IsString()
  @MaxLength(255)
  reference?: string;
}

export class NewCustomerDto {
  @ApiProperty() @IsString() @IsNotEmpty() @MaxLength(200) name: string;

  @ApiProperty() @IsString() @IsNotEmpty() @MaxLength(20) phone: string;
}

/** One POS checkout: the whole sale in a single request (design D3). */
export class CheckoutDto {
  @ApiProperty({
    description:
      'Idempotency key generated by the POS per checkout attempt; a retry returns the same order',
  })
  @IsUUID()
  client_request_id: string;

  @ApiPropertyOptional({ description: 'Existing customer' })
  @IsOptional()
  @IsUUID()
  customer_id?: string;

  @ApiPropertyOptional({
    description:
      'Quick registration (name + phone); reuses the customer if the phone exists',
    type: NewCustomerDto,
  })
  @IsOptional()
  @ValidateNested()
  @Type(() => NewCustomerDto)
  new_customer?: NewCustomerDto;

  @ApiProperty({ type: [CheckoutLineDto] })
  @IsArray()
  @ArrayMinSize(1)
  @ValidateNested({ each: true })
  @Type(() => CheckoutLineDto)
  lines: CheckoutLineDto[];

  @ApiPropertyOptional({ type: CheckoutDiscountDto })
  @IsOptional()
  @ValidateNested()
  @Type(() => CheckoutDiscountDto)
  order_discount?: CheckoutDiscountDto;

  @ApiPropertyOptional({
    description: 'Loyalty points to redeem (customer required)',
  })
  @IsOptional()
  @IsInt()
  @Min(0)
  @Max(1_000_000)
  points_to_redeem?: number;

  @ApiProperty({
    type: [CheckoutPaymentDto],
    description:
      'Zero or more payments; the unpaid balance is a credit sale (customer + pos:credit required)',
  })
  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => CheckoutPaymentDto)
  payments: CheckoutPaymentDto[];

  @ApiPropertyOptional({
    description:
      'Approval token from POST /pos/discount-approvals when the discount exceeds the role limit',
  })
  @IsOptional()
  @IsString()
  discount_approval_token?: string;

  @ApiPropertyOptional()
  @IsOptional()
  @IsString()
  @MaxLength(1000)
  notes?: string;
}
